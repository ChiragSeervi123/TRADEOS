EDITABLE = ("draft", "validated")
CANCELLABLE = ("draft", "validated", "approved", "picking")
OVERRIDABLE = {"INSUFFICIENT_AVAILABLE_STOCK", "CREDIT_LIMIT_EXCEEDED"}
LOW_CONFIDENCE = Decimal("0.85")


def add_event(db, order: Order, to_status: str, action: str, actor_id, reason: str | None = None, from_status: str | None = None):
    db.add(
        OrderStatusEvent(
            organization_id=order.organization_id,
            order_id=order.id,
            from_status=from_status if from_status is not None else order.status,
            to_status=to_status,
            action=action,
            reason=reason,
            actor_id=actor_id,
        )
    )


def snapshot_order(order: Order) -> dict:
    return {
        "order_number": order.order_number,
        "status": order.status,
        "retailer_id": str(order.retailer_id),
        "warehouse_id": str(order.warehouse_id),
        "requested_delivery_date": order.requested_delivery_date.isoformat() if order.requested_delivery_date else None,
        "notes": order.notes,
        "net_total": str(order.net_total),
        "lines": [
            {
                "line_no": l.line_no,
                "product_id": str(l.product_id) if l.product_id else None,
                "quantity": str(l.quantity),
                "unit": l.unit,
                "unit_price": str(l.unit_price),
                "scheme_discount": str(l.scheme_discount),
                "line_total": str(l.line_total),
                "is_free_goods": l.is_free_goods,
                "provenance": l.provenance,
                "extracted_values": l.extracted_values,
            }
            for l in order.lines
        ],
    }


def save_revision(db, order: Order, actor_id, reason: str):
    db.add(
        OrderRevision(
            organization_id=order.organization_id,
            order_id=order.id,
            revision=order.revision,
            snapshot=snapshot_order(order),
            reason=reason,
            actor_id=actor_id,
        )
    )


def active_rules(db, org_id) -> list[scheme_engine.Rule]:
    rows = db.execute(
        select(SchemeVersion, Scheme)
        .join(Scheme, Scheme.id == SchemeVersion.scheme_id)
        .where(SchemeVersion.organization_id == org_id, SchemeVersion.status == "active")
    ).all()
    return [
        scheme_engine.Rule(
            scheme_id=str(s.id),
            version_id=str(v.id),
            version=v.version,
            code=s.code,
            name=s.name,
            scheme_type=v.scheme_type,
            config=v.config,
            scope=v.scope or {},
            eligibility=v.eligibility or {},
            start_date=v.start_date,
            end_date=v.end_date,
            stacking=v.stacking,
            priority=v.priority,
            max_benefit=v.max_benefit,
        )
        for v, s in rows
    ]


def set_lines(ctx, order: Order, lines_in: list[dict]) -> None:
    """Replace the order's (non-free) lines from user input. Free-goods lines are
    regenerated by pricing."""
    for l in list(order.lines):
        order.lines.remove(l)
    ctx.db.flush()
    for i, li in enumerate(lines_in, start=1):
        pid = li.get("product_id")
        if pid:
            ctx.get(Product, pid, "Product")
        order.lines.append(
            OrderLine(
                organization_id=order.organization_id,
                line_no=i,
                product_id=uuid.UUID(str(pid)) if pid else None,
                source_description=li.get("source_description"),
                quantity=qty(li["quantity"]),
                unit=(li.get("unit") or "").upper() or "PCS",
                unit_price=money(li["unit_price_override"]) if li.get("unit_price_override") is not None else ZERO,
                price_override_reason=li.get("price_override_reason") if li.get("unit_price_override") is not None else None,
                provenance=li.get("provenance") or "manual",
                extracted_values=li.get("extracted_values"),
                match_confidence=li.get("match_confidence"),
            )
        )


def price_order(db, order: Order, retailer: Retailer) -> dict:
    """Recompute line amounts, schemes and totals. Returns pricing issues."""
    issues: list[dict] = []
    org_id = order.organization_id
    # Drop previous free-goods lines and scheme applications; they are regenerated.
    for l in [l for l in order.lines if l.is_free_goods]:
        order.lines.remove(l)
    for sa in db.scalars(select(SchemeApplication).where(SchemeApplication.order_id == order.id)).all():
        db.delete(sa)
    db.flush()
    lines = [l for l in order.lines if not l.is_free_goods]
    products = {p.id: p for p in db.scalars(select(Product).where(Product.id.in_([l.product_id for l in lines if l.product_id]))).all()}
    prices = pricing.resolve_prices(db, org_id, list(products), retailer, order.order_date)
    engine_lines = []
    for l in lines:
        p = products.get(l.product_id) if l.product_id else None
        l.gross_amount = l.scheme_discount = l.taxable_amount = l.tax_amount = l.line_total = ZERO
        l.manual_discount = ZERO
        if not p:
            continue
        factor = pricing.conversion_factor(db, org_id, p, l.unit, order.order_date)
        if factor is None:
            issues.append({"code": "UNIT_CONVERSION_MISSING", "severity": "error", "line_no": l.line_no, "message": f"No conversion from {l.unit} to {p.base_unit} for {p.sku}."})
            continue
        l.conversion_factor = factor
        l.base_quantity = qty(l.quantity * factor)
        l.tax_rate = p.tax_rate or ZERO
        listed = prices.get(p.id)
        l.list_price = listed[0] if listed else None
        if l.price_override_reason is not None:
            if l.list_price is not None and l.unit_price != l.list_price:
                issues.append({"code": "PRICE_OVERRIDE", "severity": "warning", "line_no": l.line_no, "message": f"{p.sku}: price {l.unit_price} differs from list price {l.list_price}.", "details": {"reason": l.price_override_reason}})
        elif l.list_price is None:
            issues.append({"code": "PRICE_NOT_FOUND", "severity": "error", "line_no": l.line_no, "message": f"No price for {p.sku} in an applicable price list."})
            l.unit_price = ZERO
            continue
        else:
            l.unit_price = l.list_price
        l.gross_amount = money(l.base_quantity * l.unit_price)
        engine_lines.append(
            scheme_engine.Line(key=l.line_no, product_id=str(p.id), sku=p.sku, brand=p.brand, category=p.category, base_qty=l.base_quantity, unit_price=l.unit_price, gross=l.gross_amount)
        )

    rules = active_rules(db, org_id)
    free_ids = {r.config.get("free_product_id") for r in rules if r.scheme_type == "buy_x_get_y" and r.config.get("free_product_id")}
    free_prices = {}
    if free_ids:
        fp = pricing.resolve_prices(db, org_id, [uuid.UUID(x) for x in free_ids], retailer, order.order_date)
        free_prices = {str(k): v[0] for k, v in fp.items()}
    result = scheme_engine.evaluate(
        scheme_engine.OrderInput(order_date=order.order_date, retailer_id=str(order.retailer_id), territory=retailer.territory, lines=engine_lines),
        rules,
        free_prices,
    )
    by_no = {l.line_no: l for l in lines}
    for l in lines:
        if l.product_id in products and l.gross_amount:
            l.scheme_discount = result.line_discount(l.line_no)
    next_no = max([l.line_no for l in lines], default=0) + 1
    order.lines  # noqa: B018
    for b in result.applied:
        db.add(
            SchemeApplication(
                organization_id=org_id,
                order_id=order.id,
                scheme_id=uuid.UUID(b.rule.scheme_id),
                scheme_version_id=uuid.UUID(b.rule.version_id),
                scheme_version=b.rule.version,
                benefit_type=b.benefit_type,
                benefit_amount=b.amount,
                free_quantity=qty(sum((f["quantity"] for f in b.free_goods), ZERO)),
                explanation=audit.jsonable(b.explanation),
            )
        )
        for f in b.free_goods:
            fpid = uuid.UUID(f["product_id"])
            fp = db.get(Product, fpid)
            if not fp or fp.organization_id != org_id:
                issues.append({"code": "SCHEME_FREE_PRODUCT_MISSING", "severity": "warning", "message": f"Scheme {b.rule.code}: free product not found."})
                continue
            order.lines.append(
                OrderLine(
                    organization_id=org_id,
                    line_no=next_no,
                    product_id=fpid,
                    source_description=f"Free goods - {b.rule.code}" + (f" (for line {f['for_line']})" if f.get("for_line") else ""),
                    quantity=f["quantity"],
                    unit=fp.base_unit,
                    conversion_factor=Decimal("1"),
                    base_quantity=f["quantity"],
                    list_price=f["unit_price"],
                    unit_price=ZERO,
                    is_free_goods=True,
                    free_scheme_id=uuid.UUID(b.rule.scheme_id),
                    provenance="scheme",
                )
            )
            next_no += 1
    for l in lines:
        if l.product_id not in products or l.gross_amount == ZERO and l.unit_price == ZERO:
            continue
        l.taxable_amount = money(l.gross_amount - l.scheme_discount - l.manual_discount)
        l.tax_amount = pct_of(l.taxable_amount, l.tax_rate)
        l.line_total = money(l.taxable_amount + l.tax_amount)
    all_lines = [l for l in order.lines if not l.is_free_goods]
    order.gross_total = money(sum((l.gross_amount for l in all_lines), ZERO))
    order.scheme_discount_total = money(sum((l.scheme_discount for l in all_lines), ZERO))
    order.discount_total = money(sum((l.manual_discount for l in all_lines), ZERO))
    order.taxable_total = money(sum((l.taxable_amount for l in all_lines), ZERO))
    order.tax_total = money(sum((l.tax_amount for l in all_lines), ZERO))
    order.net_total = money(sum((l.line_total for l in all_lines), ZERO))
    if result.skipped:
        issues.append({"code": "SCHEMES_NOT_APPLIED", "severity": "info", "message": f"{len(result.skipped)} active scheme(s) did not apply.", "details": {"skipped": result.skipped}})
    del by_no
    return {"issues": issues}


def requirements(order: Order) -> dict:
    req: dict = defaultdict(lambda: ZERO)
    for l in order.lines:
        if l.product_id and l.base_quantity:
            req[l.product_id] = qty(req[l.product_id] + l.base_quantity - (l.dispatched_quantity or ZERO))
    return dict(req)


def validate(ctx, order: Order, raise_exceptions: bool = True) -> dict:
    db = ctx.db
    retailer = db.get(Retailer, order.retailer_id)
    wh = db.get(Warehouse, order.warehouse_id)
    priced = price_order(db, order, retailer)
    issues = list(priced["issues"])
    if not [l for l in order.lines if not l.is_free_goods]:
        issues.append({"code": "NO_LINES", "severity": "error", "message": "The order has no lines."})
    if not retailer.is_active:
        issues.append({"code": "RETAILER_INACTIVE", "severity": "error", "message": f"Retailer {retailer.code} is inactive."})
    if not wh.is_active:
        issues.append({"code": "WAREHOUSE_INACTIVE", "severity": "error", "message": f"Warehouse {wh.code} is inactive."})
    products = {p.id: p for p in db.scalars(select(Product).where(Product.id.in_([l.product_id for l in order.lines if l.product_id]))).all()}
    for l in order.lines:
        if l.is_free_goods:
            continue
        if not l.product_id:
            issues.append({"code": "UNRESOLVED_PRODUCT", "severity": "error", "line_no": l.line_no, "message": f"Line {l.line_no} ('{l.source_description or ''}') has no confirmed product."})
            continue
        p = products[l.product_id]
        if not p.is_active:
            issues.append({"code": "PRODUCT_INACTIVE", "severity": "error", "line_no": l.line_no, "message": f"{p.sku} is inactive."})
        if l.quantity <= 0:
            issues.append({"code": "INVALID_QUANTITY", "severity": "error", "line_no": l.line_no, "message": "Quantity must be positive."})
        if l.provenance == "extracted" and l.match_confidence is not None and l.match_confidence < LOW_CONFIDENCE:
            issues.append({"code": "LOW_CONFIDENCE_LINE", "severity": "warning", "line_no": l.line_no, "message": f"Line {l.line_no} was matched with low confidence ({l.match_confidence})."})
    # Stock (not checked once stock is already reserved for this order).
    if order.status in ("draft", "validated"):
        shortages = []
        bals = inventory.balances(db, order.organization_id, order.warehouse_id, list(requirements(order)))
        for pid, need in requirements(order).items():
            avail = bals.get((order.warehouse_id, pid), inventory.Bal()).available
            if need > avail:
                shortages.append({"sku": products[pid].sku if pid in products else str(pid), "requested": str(need), "available": str(avail)})
        if shortages:
            issues.append({"code": "INSUFFICIENT_AVAILABLE_STOCK", "severity": "error", "overridable": True, "message": f"Insufficient available stock for {len(shortages)} product(s).", "details": {"lines": shortages}})
            if raise_exceptions:
                exc_svc.raise_exception(db, order.organization_id, "insufficient_stock", f"{order.order_number}: insufficient stock", severity="high", entity_type="order", entity_id=order.id, evidence={"shortages": shortages}, is_synthetic=order.is_synthetic)
        # Credit
        credit = receivables.credit_exposure(db, ctx.org, retailer, order.net_total, exclude_order_id=order.id)
        if credit["exceeded"]:
            issues.append({"code": "CREDIT_LIMIT_EXCEEDED", "severity": "error", "overridable": True, "message": f"Order would take exposure to {credit['exposure']} against a limit of {credit['credit_limit']}.", "details": credit})
            if raise_exceptions:
                exc_svc.raise_exception(db, order.organization_id, "credit_limit_exceeded", f"{order.order_number}: credit limit exceeded for {retailer.name}", severity="high", entity_type="order", entity_id=order.id, evidence=credit, is_synthetic=order.is_synthetic)
    # Possible duplicate: same retailer and identical product/qty set within 3 days.
    sig = sorted((str(l.product_id), str(l.base_quantity)) for l in order.lines if not l.is_free_goods and l.product_id)
    if sig:
        recent = db.scalars(
            select(Order).where(
                Order.organization_id == order.organization_id,
                Order.retailer_id == order.retailer_id,
                Order.id != order.id,
                Order.status.notin_(("cancelled", "rejected")),
                Order.order_date >= order.order_date - timedelta(days=3),
            )
        ).all()
        for o in recent:
            if sorted((str(l.product_id), str(l.base_quantity)) for l in o.lines if not l.is_free_goods and l.product_id) == sig:
                issues.append({"code": "DUPLICATE_ORDER_SUSPECTED", "severity": "warning", "message": f"Same products and quantities as {o.order_number} for this retailer within 3 days.", "details": {"order_id": str(o.id), "order_number": o.order_number}})
                if raise_exceptions:
                    exc_svc.raise_exception(db, order.organization_id, "duplicate", f"{order.order_number} may duplicate {o.order_number}", entity_type="order", entity_id=order.id, evidence={"other_order_id": str(o.id)}, dedupe_key=f"dup_order:{order.id}", is_synthetic=order.is_synthetic)
                break
    threshold = ctx.org.setting("approval_threshold") if ctx.org else None
    if threshold is not None and order.net_total > Decimal(str(threshold)):
        issues.append({"code": "SENIOR_APPROVAL_REQUIRED", "severity": "info", "message": f"Net total exceeds the approval threshold {threshold}; an owner or admin must approve."})
    blocking = [i for i in issues if i["severity"] == "error" and not i.get("overridable")]
    overridable = [i for i in issues if i["severity"] == "error" and i.get("overridable")]
    result = {
        "valid": not blocking and not overridable,
        "blocking": len(blocking),
        "overridable": len(overridable),
        "issues": issues,
        "validated_at": utcnow().isoformat(),
    }
    order.validation = audit.jsonable(result)
    if order.status in EDITABLE:
        new_status = "validated" if not blocking else "draft"
        if new_status != order.status:
            add_event(db, order, new_status, "validate", ctx.user.id if ctx.user else None)
            order.status = new_status
    return result


def create_order(ctx, *, retailer_id, warehouse_id, lines, order_date: date | None = None, requested_delivery_date=None, notes=None, channel="manual", source_id=None, idempotency_key=None, is_synthetic=False) -> Order:
    retailer = ctx.get(Retailer, retailer_id, "Retailer")
    wh = ctx.get(Warehouse, warehouse_id, "Warehouse")
    order = Order(
        organization_id=ctx.org_id,
        order_number=next_number(ctx.db, Order, ctx.org_id, "order_number", "SO"),
        retailer_id=retailer.id,
        warehouse_id=wh.id,
        status="draft",
        order_date=order_date or date.today(),
        requested_delivery_date=requested_delivery_date,
        notes=notes,
        channel=channel,
        source_id=source_id,
        currency=ctx.org.currency,
        idempotency_key=idempotency_key,
        created_by_id=ctx.user.id if ctx.user else None,
        is_synthetic=is_synthetic,
    )
    ctx.db.add(order)
    ctx.db.flush()
    set_lines(ctx, order, lines)
    ctx.db.flush()
    add_event(ctx.db, order, "draft", "create", order.created_by_id, from_status="")
    validate(ctx, order)
    audit.record(ctx, "order.create", "order", order.id, after={"order_number": order.order_number, "net_total": str(order.net_total), "lines": len(order.lines), "channel": channel})
    return order


def update_draft(ctx, order: Order, *, lines=None, retailer_id=None, warehouse_id=None, requested_delivery_date=None, notes=None, fields_set=()) -> Order:
    if order.status not in EDITABLE:
        raise conflict("ORDER_NOT_EDITABLE", f"Orders in status '{order.status}' cannot be edited. Use amend.")
    save_revision(ctx.db, order, ctx.user.id, "edit")
    order.revision += 1
    if retailer_id:
        order.retailer_id = ctx.get(Retailer, retailer_id, "Retailer").id
    if warehouse_id:
        order.warehouse_id = ctx.get(Warehouse, warehouse_id, "Warehouse").id
    if "requested_delivery_date" in fields_set:
        order.requested_delivery_date = requested_delivery_date
    if "notes" in fields_set:
        order.notes = notes
    if lines is not None:
        set_lines(ctx, order, lines)
    ctx.db.flush()
    if order.status == "validated":
        add_event(ctx.db, order, "draft", "edit", ctx.user.id)
        order.status = "draft"
    validate(ctx, order)
    audit.record(ctx, "order.edit", "order", order.id, meta={"revision": order.revision})
    return order


def approve(ctx, order: Order, *, stock_override_reason: str | None = None, credit_override_reason: str | None = None) -> tuple[Order, bool]:
    """Returns (order, changed). Already-approved orders are returned unchanged (idempotent)."""
    if order.status in ("approved", "picking", "dispatched", "delivered", "partially_fulfilled"):
        return order, False
    if order.status not in EDITABLE:
        raise conflict("INVALID_STATUS", f"Cannot approve an order in status '{order.status}'.")
    result = validate(ctx, order)
    codes = {i["code"] for i in result["issues"] if i["severity"] == "error"}
    blocking = codes - OVERRIDABLE
    if blocking:
        raise AppError("ORDER_INVALID", "The order has validation errors that must be fixed before approval.", 422, {"issues": [i for i in result["issues"] if i["code"] in blocking]})
    if "SENIOR_APPROVAL_REQUIRED" in {i["code"] for i in result["issues"]} and ctx.role not in ("org_owner", "org_admin"):
        raise forbidden("This order exceeds the approval threshold and must be approved by an owner or admin.")
    allow_shortfall = False
    if "INSUFFICIENT_AVAILABLE_STOCK" in codes:
        if not stock_override_reason:
            shortages = next(i for i in result["issues"] if i["code"] == "INSUFFICIENT_AVAILABLE_STOCK")["details"]["lines"]
            raise AppError("INSUFFICIENT_AVAILABLE_STOCK", "The requested quantity exceeds available stock.", 409, {**shortages[0], "lines": shortages})
        if ctx.org.setting("negative_stock_policy") != "allow_with_override":
            raise AppError("OVERRIDE_NOT_PERMITTED", "Organisation policy blocks reservations beyond available stock.", 409)
        ctx.require("orders.override")
        allow_shortfall = True
    if "CREDIT_LIMIT_EXCEEDED" in codes:
        if not credit_override_reason:
            raise AppError("CREDIT_LIMIT_EXCEEDED", "This order exceeds the retailer's credit limit.", 409, next(i for i in result["issues"] if i["code"] == "CREDIT_LIMIT_EXCEEDED").get("details"))
        ctx.require("orders.override")
        if not ctx.can("finance.approve") and ctx.role not in ("org_owner", "org_admin", "operations_manager"):
            raise forbidden("Credit overrides require an authorised approver.")
    shortfalls = inventory.reserve(
        ctx.db,
        ctx.org_id,
        warehouse_id=order.warehouse_id,
        requirements=requirements(order),
        source_type="order",
        source_id=order.id,
        actor_id=ctx.user.id,
        allow_shortfall=allow_shortfall,
        reason=stock_override_reason,
        is_synthetic=order.is_synthetic,
    )
    if allow_shortfall or credit_override_reason:
        order.stock_override_reason = stock_override_reason if allow_shortfall else None
        order.credit_override_reason = credit_override_reason
        order.override_by_id = ctx.user.id
    prev = order.status
    order.status = "approved"
    order.approved_by_id = ctx.user.id
    order.approved_at = utcnow()
    add_event(ctx.db, order, "approved", "approve", ctx.user.id, reason="; ".join(r for r in (stock_override_reason, credit_override_reason) if r) or None, from_status=prev)
    from app.services import fulfilment

    pl = fulfilment.create_pick_list(ctx, order)
    audit.record(
        ctx,
        "order.approve",
        "order",
        order.id,
        before={"status": prev},
        after={"status": "approved", "net_total": str(order.net_total), "pick_list": pl.pick_number if pl else None},
        meta={"stock_override_reason": stock_override_reason if allow_shortfall else None, "credit_override_reason": credit_override_reason, "shortfalls": shortfalls},
    )
    return order, True


def reject(ctx, order: Order, reason: str) -> Order:
    if order.status not in EDITABLE:
        raise conflict("INVALID_STATUS", f"Cannot reject an order in status '{order.status}'.")
    add_event(ctx.db, order, "rejected", "reject", ctx.user.id, reason)
    prev = order.status
    order.status = "rejected"
    audit.record(ctx, "order.reject", "order", order.id, before={"status": prev}, after={"status": "rejected"}, meta={"reason": reason})
    return order


def _cancel_open_picklists(ctx, order: Order):
    for pl in ctx.db.scalars(select(PickList).where(PickList.order_id == order.id, PickList.status.in_(("open", "picking", "picked")))).all():
        pl.status = "cancelled"


def cancel(ctx, order: Order, reason: str) -> Order:
    if order.status == "cancelled":
        return order
    if order.status not in CANCELLABLE:
        raise conflict("INVALID_STATUS", f"Orders in status '{order.status}' cannot be cancelled (stock has left the warehouse; use a return).")
    released = inventory.release_all(ctx.db, ctx.org_id, source_type="order", source_id=order.id, actor_id=ctx.user.id, reason=f"Order cancelled: {reason}")
    _cancel_open_picklists(ctx, order)
    add_event(ctx.db, order, "cancelled", "cancel", ctx.user.id, reason)
    prev = order.status
    order.status = "cancelled"
    audit.record(ctx, "order.cancel", "order", order.id, before={"status": prev}, after={"status": "cancelled"}, meta={"reason": reason, "reservations_released": released})
    return order


def amend(ctx, order: Order, reason: str) -> Order:
    """Controlled amendment of an approved order: release reservations, snapshot a
    revision and return it to draft for edit + re-approval."""
    if order.status not in ("approved", "picking"):
        raise conflict("INVALID_STATUS", f"Only approved orders not yet dispatched can be amended (status '{order.status}').")
    save_revision(ctx.db, order, ctx.user.id, f"amendment: {reason}")
    order.revision += 1
    inventory.release_all(ctx.db, ctx.org_id, source_type="order", source_id=order.id, actor_id=ctx.user.id, reason=f"Order amendment: {reason}")
    _cancel_open_picklists(ctx, order)
    add_event(ctx.db, order, "draft", "amend", ctx.user.id, reason)
    prev = order.status
    order.status = "draft"
    order.approved_at = None
    order.approved_by_id = None
    validate(ctx, order, raise_exceptions=False)
    audit.record(ctx, "order.amend", "order", order.id, before={"status": prev}, after={"status": order.status}, meta={"reason": reason, "revision": order.revision})
    return order
